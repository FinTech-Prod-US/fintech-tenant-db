USE ${DB_NAME_BUSINESS_RULES};

INSERT INTO CREDIT_POSTING_RULE
  (COLLECTION_CODE, GRANULARITY, CREDIT_SIDE, CREDIT_ACCOUNT_RESOLUTION, CREDIT_CARRIER,
   DEBIT_SIDE, DEBIT_ACCOUNT_RESOLUTION, BOOKED_AT, INVARIANT, Active, EffectiveDate)
SELECT v.* FROM (
  SELECT 'OUTCLFATM' AS C,'PER_DEPOSIT' AS G,'DDA' AS CS,'DDA_FROM_ITEM' AS CR,'LEADING_ITEM' AS CC,'GL' AS DS,'FLOAT_CLEARING_GL' AS DR,'POSTING' AS B,'SUM_DEBIT_EQ_CREDIT' AS I,'Y' AS A,CURDATE() AS E
  UNION ALL SELECT 'OUTCLFMOB','PER_DEPOSIT','DDA','DDA_FROM_ITEM','LEADING_ITEM','GL','FLOAT_CLEARING_GL','POSTING','SUM_DEBIT_EQ_CREDIT','Y',CURDATE()
  UNION ALL SELECT 'OUTCLFRDC','PER_DEPOSIT','DDA','DDA_FROM_ITEM','LEADING_ITEM','GL','FLOAT_CLEARING_GL','POSTING','SUM_DEBIT_EQ_CREDIT','Y',CURDATE()
  UNION ALL SELECT 'OUTCLFLBX','PER_DEPOSIT','DDA','DDA_FROM_ITEM','LEADING_ITEM','GL','FLOAT_CLEARING_GL','POSTING','SUM_DEBIT_EQ_CREDIT','Y',CURDATE()
  UNION ALL SELECT 'OUTCLFCOR','PER_DEPOSIT','DDA','DDA_FROM_ITEM','LEADING_ITEM','GL','FLOAT_CLEARING_GL','POSTING','SUM_DEBIT_EQ_CREDIT','Y',CURDATE()
  UNION ALL SELECT 'INCLRF','PER_ITEM','GL','RETURN_SUSPENSE',NULL,'DDA','DDA_FROM_ORIGINAL_DEPOSIT','POSTING','SUM_DEBIT_EQ_CREDIT','Y',CURDATE()
  UNION ALL SELECT 'INCLRB','PER_ITEM','GL','RETURN_SUSPENSE',NULL,'DDA','DDA_FROM_ORIGINAL_DEPOSIT','POSTING','SUM_DEBIT_EQ_CREDIT','Y',CURDATE()
  UNION ALL SELECT 'OUTCLRDDA','PER_ITEM','DDA','DDA_EFFECTIVE',NULL,'GL','RETURN_SUSPENSE','POSTING','SUM_DEBIT_EQ_CREDIT','Y',CURDATE()
  UNION ALL SELECT 'INCLEARING_RETURN','PER_ITEM','DDA','DDA_EFFECTIVE',NULL,'GL','RETURN_SUSPENSE','POSTING','SUM_DEBIT_EQ_CREDIT','Y',CURDATE()
  UNION ALL SELECT 'OUTCLEARING_RETURN','PER_ITEM','GL','RETURN_SUSPENSE',NULL,'DDA','DDA_FROM_ORIGINAL_DEPOSIT','POSTING','SUM_DEBIT_EQ_CREDIT','Y',CURDATE()
) v
WHERE NOT EXISTS (SELECT 1 FROM CREDIT_POSTING_RULE r WHERE r.COLLECTION_CODE = v.C AND r.Active = 'Y');
SELECT 'credit posting rule per code applied' AS result;
