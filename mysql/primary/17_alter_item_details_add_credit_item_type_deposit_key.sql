-- SPEC_09 Phase 3: ITEM_DETAILS.CREDIT_ITEM_TYPE + DEPOSIT_KEY (idempotent).
-- Run against: {DB_NAME_PRIMARY}. Re-running changes nothing.
-- ============================================================================
USE ${DB_NAME_PRIMARY};

-- CREDIT_ITEM_TYPE
SET @c := (SELECT COUNT(*) FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=DATABASE()
           AND TABLE_NAME='ITEM_DETAILS' AND COLUMN_NAME='CREDIT_ITEM_TYPE');
SET @s := IF(@c=0,
 'ALTER TABLE ITEM_DETAILS ADD COLUMN CREDIT_ITEM_TYPE VARCHAR(16) NULL COMMENT ''Non-payable credit kind: SYNTHESIZED_CL | DEPOSIT_TICKET. NON-PAYABLE PREDICATE EVERYWHERE = COALESCE(SYNTHESIZED_CREDIT,0)=1 OR CREDIT_ITEM_TYPE IS NOT NULL (SPEC_09 Phase 3)''',
 'SELECT ''ITEM_DETAILS.CREDIT_ITEM_TYPE exists'' AS result');
PREPARE stmt FROM @s; EXECUTE stmt; DEALLOCATE PREPARE stmt;

-- DEPOSIT_KEY
SET @c := (SELECT COUNT(*) FROM information_schema.COLUMNS WHERE TABLE_SCHEMA=DATABASE()
           AND TABLE_NAME='ITEM_DETAILS' AND COLUMN_NAME='DEPOSIT_KEY');
SET @s := IF(@c=0,
 'ALTER TABLE ITEM_DETAILS ADD COLUMN DEPOSIT_KEY VARCHAR(64) NULL COMMENT ''Scoped per-deposit key F<fileId>-C<x9ClId>-B<x9BundleId>-D<seq7>[-<run>] (SPEC_09 Phase 3)''',
 'SELECT ''ITEM_DETAILS.DEPOSIT_KEY exists'' AS result');
PREPARE stmt FROM @s; EXECUTE stmt; DEALLOCATE PREPARE stmt;

-- index on DEPOSIT_KEY
SET @i := (SELECT COUNT(*) FROM information_schema.STATISTICS WHERE TABLE_SCHEMA=DATABASE()
           AND TABLE_NAME='ITEM_DETAILS' AND INDEX_NAME='IDX_ITEM_DETAILS_DEPOSIT_KEY');
SET @s := IF(@i=0, 'CREATE INDEX IDX_ITEM_DETAILS_DEPOSIT_KEY ON ITEM_DETAILS (DEPOSIT_KEY)',
             'SELECT ''IDX_ITEM_DETAILS_DEPOSIT_KEY exists'' AS result');
PREPARE stmt FROM @s; EXECUTE stmt; DEALLOCATE PREPARE stmt;

-- D1 backfill (re-run safe: only fills NULLs)
UPDATE ITEM_DETAILS SET CREDIT_ITEM_TYPE='SYNTHESIZED_CL'
 WHERE SYNTHESIZED_CREDIT=1 AND CREDIT_ITEM_TYPE IS NULL;

-- value guard (added AFTER the backfill so existing rows already satisfy it)
SET @k := (SELECT COUNT(*) FROM information_schema.TABLE_CONSTRAINTS WHERE CONSTRAINT_SCHEMA=DATABASE()
           AND TABLE_NAME='ITEM_DETAILS' AND CONSTRAINT_NAME='CK_ITEM_DETAILS_CREDIT_ITEM_TYPE' AND CONSTRAINT_TYPE='CHECK');
SET @s := IF(@k=0,
 'ALTER TABLE ITEM_DETAILS ADD CONSTRAINT CK_ITEM_DETAILS_CREDIT_ITEM_TYPE CHECK (CREDIT_ITEM_TYPE IS NULL OR CREDIT_ITEM_TYPE IN (''SYNTHESIZED_CL'',''DEPOSIT_TICKET''))',
 'SELECT ''CK_ITEM_DETAILS_CREDIT_ITEM_TYPE exists'' AS result');
PREPARE stmt FROM @s; EXECUTE stmt; DEALLOCATE PREPARE stmt;
