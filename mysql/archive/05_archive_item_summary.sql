-- ============================================================================
-- ARCHIVE_ITEM_SUMMARY — denormalized research row, one per item per business day
-- (SPEC_14 7.2, D6). The retrieval API reads this table first, then joins the
-- identical-copy tables and ARCHIVE_ITEM_AUDIT_TRAIL for the full lifecycle.
--
-- Built by the sweep (not a column-for-column copy): ITEM_DETAILS +
-- ITEM_DETAILS_ENRICHED + CASH_LETTER_DETAILS + INBOUND_FILE_DETAILS +
-- POSTING_EOD_FILES + IA_ARCHIVE_FILE + ITEM_AUDIT_TRAIL aggregates +
-- ITEM_IMAGE_REF + CUSTOMER_ADVICE. Column types are copied from the source columns.
-- COLLECTION_GROUP is derived (COLLECTION_CODE_GROUP.GROUP_NAME, varchar(20)).
-- Partitioned like the other archive tables: no FKs, PK includes ARCHIVE_BUS_DATE.
-- ============================================================================
USE ${DB_NAME_ARCHIVE};

CREATE TABLE IF NOT EXISTS `ARCHIVE_ITEM_SUMMARY` (
  -- Identity
  `PAYMENT_ID` bigint NOT NULL,
  `ARCHIVE_BUS_DATE` DATE NOT NULL COMMENT 'Business date of the archived day (partition key)',
  `BDAY_ID` bigint DEFAULT NULL,
  `PAYMENT_TRACKING_NUMBER` varchar(64) DEFAULT NULL,
  `ORIG_MICR_RT` varchar(9) DEFAULT NULL,
  `ORIG_MICR_ACCOUNT` varchar(31) DEFAULT NULL,
  `ORIG_MICR_SERIAL` varchar(15) DEFAULT NULL,
  `AMOUNT` decimal(15,2) DEFAULT NULL,
  `DEBIT_CREDIT_IND` char(1) DEFAULT NULL,
  -- Source file / cash letter
  `FILE_ID` bigint DEFAULT NULL,
  `CUST_FILENAME` varchar(255) DEFAULT NULL,
  `RCVD_FILENAME` varchar(255) DEFAULT NULL,
  `CASHLTR_ID` bigint DEFAULT NULL,
  `COLLECTION_CODE` varchar(10) DEFAULT NULL,
  `COLLECTION_GROUP` varchar(20) DEFAULT NULL COMMENT 'Derived: COLLECTION_CODE_GROUP.GROUP_NAME',
  `BIN_NUMBER` int DEFAULT NULL,
  -- Processing / disposition
  `ROUTING_DESTINATION` varchar(50) DEFAULT NULL,
  `ROUTING_REASON` varchar(500) DEFAULT NULL,
  `DISPOSITION_STATUS` varchar(20) DEFAULT NULL,
  `PROCESSING_STATUS` varchar(30) DEFAULT NULL,
  `FORWARD_ENDPOINT` varchar(20) DEFAULT NULL,
  `RETURN_ENDPOINT` varchar(20) DEFAULT NULL,
  `IQV_STATUS` varchar(30) DEFAULT NULL,
  `DQV_STATUS` varchar(30) DEFAULT NULL,
  `BR_ENGINE_STATUS` varchar(30) DEFAULT NULL,
  `DUP_DETECT_STATUS` varchar(30) DEFAULT NULL,
  `CDE_REPAIR_STATUS` varchar(30) DEFAULT NULL,
  -- Downstream
  `POSTING_EXTRACTED_STATUS` char(1) DEFAULT NULL COMMENT 'From CASH_LETTER_DETAILS',
  `IMAGE_ARCHIVED_STATUS` char(1) DEFAULT NULL COMMENT 'From CASH_LETTER_DETAILS',
  `POSTING_FILE_NAME` varchar(255) DEFAULT NULL,
  `POSTING_FILE_S3_KEY` varchar(512) DEFAULT NULL,
  `IA_ARCHIVE_FILE_ID` bigint DEFAULT NULL,
  `IA_ARCHIVE_STATUS` varchar(30) DEFAULT NULL,
  `IA_ARCHIVE_FILE_S3_KEY` varchar(500) DEFAULT NULL,
  `ADVICE_REFERENCE` varchar(50) DEFAULT NULL,
  -- Who / when
  `FIRST_EVENT_AT` datetime(3) DEFAULT NULL,
  `LAST_EVENT_AT` datetime(3) DEFAULT NULL,
  `LAST_PERFORMED_BY` varchar(100) DEFAULT NULL,
  `OPS_OPERATOR_ID` varchar(50) DEFAULT NULL,
  `OPS_DECISION` varchar(20) DEFAULT NULL,
  `OPS_DECISION_TIMESTAMP` datetime DEFAULT NULL,
  `AUDIT_EVENT_COUNT` int DEFAULT NULL,
  -- Images (S3 references only)
  `FRONT_S3_KEY` varchar(400) DEFAULT NULL,
  `BACK_S3_KEY` varchar(400) DEFAULT NULL,
  `IMAGE_BUCKET` varchar(120) DEFAULT NULL,
  `IMAGE_SOURCE` varchar(16) DEFAULT NULL COMMENT 'S3 | BLOB_FALLBACK (no ITEM_IMAGE_REF row: logical locator = PAYMENT_ID + ARCHIVE_BUS_DATE)',
  `ARCHIVED_AT` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT 'When the sweep built this row',
  PRIMARY KEY (`PAYMENT_ID`, `ARCHIVE_BUS_DATE`),
  KEY `idx_ais_tracking` (`PAYMENT_TRACKING_NUMBER`),
  KEY `idx_ais_micr_amount` (`ORIG_MICR_ACCOUNT`, `ORIG_MICR_RT`, `AMOUNT`),
  KEY `idx_ais_file` (`FILE_ID`),
  KEY `idx_ais_bday` (`BDAY_ID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
PARTITION BY RANGE (TO_DAYS(ARCHIVE_BUS_DATE)) (
  PARTITION p202601 VALUES LESS THAN (TO_DAYS('2026-02-01')),
